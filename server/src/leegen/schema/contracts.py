def views_fixtures(problems: dict[str, Problem]) -> dict[str, Any]:
    cases: list[dict[str, Any]] = []
    for pid, p in problems.items():
        cases.append({"fn": "problem_summary", "args": {"problem": pid},
                      "result": problem_summary(p)})
        cases.append({"fn": "public_problem", "args": {"problem": pid},
                      "result": public_problem(p)})
    for last in [None, {"status": "passed"}, {"status": "failed"}, {"status": "error"}]:
        cases.append({"fn": "run_status", "args": {"last_run": last}, "result": run_status(last)})
    run = {"status": "failed", "passed": 1, "total": 3, "executor": "browser", "device": "cpu",
           "error": None, "compile_output": None, "metrics": [],
           "tests": [{"name": "a", "status": "pass", "visible": True, "input": [1]},
                     {"name": "b", "status": "fail", "visible": True, "input": [2],
                      "expected": 3, "actual": 4, "message": "nope", "section": "basics"},
                     {"name": "c", "status": "error", "visible": False, "message": "boom",
                      "stdout": "hi"}]}
    for full in (False, True):
        cases.append({"fn": "brief_run", "args": {"result": run, "full": full},
                      "result": brief_run(run, full=full)})
    cases.append({"fn": "brief_run", "args": {"result": None, "full": False}, "result": None})
    return {"cases": cases}


# ------------------------------------------------------------------ write / check


FIXTURE_PROBLEMS = ["merge-ranges", "iterators-and-await", "kv-cache-basics",
                    "cuda-vector-add", "webgpu-tiled-matmul"]


def outputs() -> dict[Path, str]:
    root = settings().root
    problems = {pid: parse_problem_yaml((root / "problems" / f"{pid}.yaml").read_text())
                for pid in FIXTURE_PROBLEMS}
    records = _all_required(_Records.model_json_schema(mode="serialization"))
    inputs = _Inputs.model_json_schema(mode="validation")
    problem_data = {pid: p.model_dump(mode="json") for pid, p in problems.items()}
    return {
        root / "schema" / "problem.schema.json": json.dumps(problem_json_schema(), indent=2) + "\n",
        root / "contracts" / "records.schema.json": _dump(records),
        root / "contracts" / "inputs.schema.json": _dump(inputs),
        root / "contracts" / "tools.json": _dump(tool_manifest()),
        root / "contracts" / "fixtures" / "problems.json": _dump(problem_data),
        root / "contracts" / "fixtures" / "review.json": _dump(review_fixtures(problems)),
        root / "contracts" / "fixtures" / "views.json": _dump(views_fixtures(problems)),
        root / "web" / "src" / "contracts" / "generated.ts": typescript(records, inputs),
    }


def write_all() -> list[Path]:
    written = []
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
        written.append(path)
    return written


def check_all() -> list[Path]:
    """Paths whose committed content differs from what the code generates."""
    return [p for p, text in outputs().items() if not p.exists() or p.read_text() != text]

