def _all_required(schema: dict[str, Any]) -> dict[str, Any]:
    """Serialized pydantic models always contain every field, defaults included."""
    for d in [schema, *schema.get("$defs", {}).values()]:
        if d.get("type") == "object" and "properties" in d:
            d["required"] = list(d["properties"])
    return schema


def _dump(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------ TypeScript emitter


def _pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def _ts(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = []
            for sub in s[key]:
                t = _ts(sub)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = _ts(s["items"]) if "items" in s else "unknown"
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" in s:
            return _ts_object(s, indent="  ")
        extra = s.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {_ts(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def _ts_object(s: dict[str, Any], indent: str = "") -> str:
    required = set(s.get("required", []))
    lines = ["{"]
    for key, prop in s.get("properties", {}).items():
        doc = prop.get("description")
        if doc:
            lines.append(f"{indent}  /** {doc.splitlines()[0]} */")
        opt = "" if key in required else "?"
        lines.append(f"{indent}  {key}{opt}: {_ts(prop)};")
    lines.append(indent + "}")
    return "\n".join(lines)


def typescript(*schemas: dict[str, Any]) -> str:
    out = ["// Generated by `uv run leegen schema` from server/src/leegen/core. Do not edit.",
           ""]
    seen: set[str] = set()
    for schema in schemas:
        for name, d in schema.get("$defs", {}).items():
            if name in seen:
                continue
            seen.add(name)
            if d.get("description"):
                out.append(f"/** {d['description'].splitlines()[0]} */")
            if d.get("type") == "object" and "properties" in d:
                out.append(f"export interface {name} {_ts_object(d)}")
            else:
                out.append(f"export type {name} = {_ts(d)};")
            out.append("")
        for key, prop in schema.get("properties", {}).items():
            name = _pascal(key)
            if name in seen or prop.get("$ref", "").endswith("/" + name):
                continue
            seen.add(name)
            out.append(f"export type {name} = {_ts(prop)};")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


# ------------------------------------------------------------------ tool manifest


async def _mcp_tools() -> list[dict[str, Any]]:
    from mcp import Client

    from leegen.mcp_server import build_mcp

    async with Client(build_mcp()) as client:
        return [t.model_dump(mode="json", exclude_none=True, by_alias=True)
                for t in (await client.list_tools()).tools]


def tool_manifest() -> dict[str, Any]:
    tools = []
    for t in sorted(asyncio.run(_mcp_tools()), key=lambda t: t["name"]):
        spec = TOOLS[t["name"]]
        tools.append({
            "name": t["name"],
            "title": spec.title,
            "description": t.get("description", ""),
            "inputSchema": t["inputSchema"],
            "annotations": {"readOnlyHint": spec.read_only,
                            "consequentialHint": spec.consequential,
                            "untrustedContentHint": spec.untrusted_output},
            "browser": spec.browser,
        })
    missing = set(TOOLS) - {t["name"] for t in tools}
    if missing:
        raise RuntimeError(f"toolspec lists tools the MCP server lacks: {sorted(missing)}")
    return {"version": 1, "tools": tools}


# ------------------------------------------------------------------ conformance fixtures


def _ids() -> Any:
    counter = itertools.count(1)
    return lambda: f"id{next(counter)}"


def _clock() -> Any:
    counter = itertools.count(1)
    return lambda: float(1_700_000_000 + next(counter))


def _case(fn: str, args: dict[str, Any], call: Any) -> dict[str, Any]:
    try:
        return {"fn": fn, "args": args, "result": call()}
    except (ValueError, LookupError) as exc:
        return {"fn": fn, "args": args, "error": str(exc)}


