"""Generate contracts/ (and the web app's TypeScript types) from the Python source of truth.

    uv run leegen schema            # write everything
    uv run leegen schema --check    # exit 1 if anything is out of date (CI)

Outputs:
- schema/problem.schema.json         problem YAML format (authors, editors)
- contracts/records.schema.json      wire records + UI events (serialization shape)
- contracts/inputs.schema.json       problem / environment / runner request (input shape)
- contracts/tools.json               agent tools: MCP definitions + WebMCP hints
- contracts/fixtures/*.json          golden cases the TypeScript ports must reproduce
- web/src/contracts/generated.ts     TypeScript types for the records, events and inputs
"""

