import { Clock, Cpu, Gauge, ListChecks, Square, Terminal } from "lucide-react";
import { useEffect, useState } from "react";
import type { PublicSection, RunResult, TestResult } from "../lib/api";
import { bareSection, groupBySection } from "../lib/sections";
import { CaseGroups } from "./CaseGroups";
import { Markdown } from "./Markdown";
import { Button, Chip, cx } from "./ui";
import { Value } from "./Value";

const STATUS_TEXT: Record<RunResult["status"], string> = {
  passed: "Accepted",
  failed: "Wrong Answer",
  error: "Error",
  timeout: "Time Limit Exceeded",
  compile_error: "Compile Error",
  cancelled: "Cancelled",
};

function InputView({ input, params }: { input: unknown; params: string[] }) {
  const obj = input as { args?: unknown[]; kwargs?: Record<string, unknown>; generated?: string; calls?: unknown } | null;
  if (!obj || typeof obj !== "object" || Array.isArray(obj)) return <Value label="Input" value={input} />;
  return (
    <>
      {obj.generated && <Value label="Input" value={`generated by ${obj.generated}`} raw mono={false} />}
      {(obj.args ?? []).map((a, i) => (
        <Value key={i} label={params[i] ?? `arg${i + 1}`} value={a} />
      ))}
      {Object.entries(obj.kwargs ?? {}).map(([k, v]) => (
        <Value key={k} label={k} value={v} />
      ))}
      {obj.calls != null && <Value label="calls" value={obj.calls} />}
    </>
  );
}

export function ResultPanel({
  result,
  running,
  onCancel,
  params = [],
  sections = [],
  phase = null,
}: {
  result: RunResult | null;
  running: boolean;
  onCancel: () => void;
  params?: string[];
  sections?: PublicSection[];
  phase?: { phase: string; detail: string } | null;
}) {
  const [sel, setSel] = useState(0);
  useEffect(() => {
    if (!result) return;
    const firstBad = result.tests.findIndex((t) => t.status !== "pass");
    setSel(firstBad >= 0 ? firstBad : 0);
  }, [result?.run_id]);

  if (running)
    return (
      <div className="panel-body">
        <div className="running">
          <div className="running-bar" />
          <div className="row between">
            <span className="muted">
              {phase?.phase === "loading"
                ? `${phase.detail}…`
                : phase?.phase === "preparing"
                ? `Preparing ${phase.detail}… (the first run of an environment installs its packages)`
                : phase?.phase === "queued"
                  ? `Queued: ${phase.detail}, waiting for resources…`
                  : phase?.detail
                    ? `Running on ${phase.detail}…`
                    : "Running…"}
            </span>
            <Button variant="ghost" icon={Square} onClick={onCancel}>
              Cancel
            </Button>
          </div>
        </div>
      </div>
    );
  if (!result)
    return (
      <div className="empty">
        <Terminal size={20} strokeWidth={1.6} />
        <span>
          Run your code to see results. <kbd>⌘</kbd> <kbd>↵</kbd>
        </span>
      </div>
    );

  const t: TestResult | undefined = result.tests[sel];
  const ok = result.status === "passed";
  return (
    <div className="panel-body">
      <div className="result-head">
        <span className={"result-status " + (ok ? "ok" : "bad")}>{STATUS_TEXT[result.status]}</span>
        {result.total > 0 && (
          <Chip icon={ListChecks} tone={ok ? "pass" : "neutral"}>
            {result.passed} / {result.total} tests passed
          </Chip>
        )}
        <span className="spacer" />
        <Chip icon={Cpu} title="Executor · device">
          {result.executor}
          {result.device ? ` · ${result.device}` : ""}
        </Chip>
        <Chip icon={Clock} title="Wall time">
          {(result.duration_ms / 1000).toFixed(2)}s
        </Chip>
      </div>

      {result.error && <pre className="error-block">{result.error}</pre>}
      {result.compile_output && <pre className="error-block">{result.compile_output}</pre>}

      {result.metrics.length > 0 && (
        <div className="metrics">
          {result.metrics.map((m) => (
            <div key={m.name} className="metric">
              <span className="metric-label">
                <Gauge size={13} strokeWidth={1.9} /> {m.name}
              </span>
              <span className="metric-value tabular">
                {m.value.toFixed(3)} <small>{m.unit}</small>
              </span>
              {m.reference != null && (
                <span className="metric-ref tabular">
                  reference {m.reference.toFixed(3)} {m.unit}
                </span>
              )}
            </div>
          ))}
        </div>
      )}

      {result.tests.length > 0 && (
        <CaseGroups
          groups={groupBySection(
            result.tests.map((x, index) => ({ ...x, index })),
            sections,
            bareSection,
          )}
          sectioned={sections.length > 0 || result.tests.some((x) => x.section)}
          render={(x) => (
            <button
              key={x.name + x.index}
              className={cx("pill", x.status === "pass" ? "pass" : "fail", sel === x.index && "active")}
              onClick={() => setSel(x.index)}
            >
              <span className="status-dot" />
              Test {x.index + 1}
              {!x.visible && !x.custom && <span className="pill-note">hidden</span>}
            </button>
          )}
        />
      )}

      {t && (
        <div className="case">
          <div className="row">
            <Chip tone={t.status === "pass" ? "pass" : "fail"}>
              <span className="cap">{t.status}</span>
            </Chip>
          </div>
          {t.description && <div className="muted"><Markdown source={t.description} /></div>}
          {!t.visible && t.status === "pass" && <p className="muted small">Hidden test: details are shown only when it fails.</p>}
          {t.input != null && <InputView input={t.input} params={params} />}
          {t.actual != null || t.expected != null ? (
            <>
              <Value label="Output" value={t.actual} tone={t.status === "pass" ? undefined : "fail"} />
              <Value label="Expected" value={t.expected} />
            </>
          ) : null}
          {t.message && <Value label="Message" value={t.message} raw />}
          {t.stdout && <Value label="Stdout" value={t.stdout} raw />}
          {t.duration_ms != null && <div className="muted small tabular">{t.duration_ms.toFixed(1)} ms</div>}
        </div>
      )}
      {!t && result.stderr && <Value label="stderr" value={result.stderr} raw />}
    </div>
  );
}
