import { FlaskConical, Plus, Trash2 } from "lucide-react";
import { useEffect, useState } from "react";
import type { CustomTest, Problem, TestInput } from "../lib/api";
import { groupBySection } from "../lib/sections";
import { CaseGroups } from "./CaseGroups";
import { Markdown } from "./Markdown";
import { cx, IconButton } from "./ui";
import { formatValue, Value } from "./Value";

interface Props {
  problem: Problem;
  customTests: CustomTest[];
  onChangeCustom: (tests: CustomTest[]) => void;
  onOpenFile: (path: string) => void;
}

function paramNames(problem: Problem, input: TestInput | null | undefined): string[] {
  const n = input?.args?.length ?? 0;
  const names = problem.judge.params ?? [];
  return Array.from({ length: Math.max(n, names.length) }, (_, i) => names[i] ?? `arg${i + 1}`);
}

export function TestcasePanel({ problem, customTests, onChangeCustom, onOpenFile }: Props) {
  if (problem.judge.kind !== "function") {
    const testFiles = problem.files.filter((f) => /(^|\/)test_[^/]*\.py$/.test(f.path));
    return (
      <div className="panel-body">
        <p className="muted suite-note">
          <FlaskConical size={16} strokeWidth={1.7} />
          <span>
          This problem is checked by a test suite. Visible tests are in{" "}
          {testFiles.length ? (
            testFiles.map((f, i) => (
              <span key={f.path}>
                {i > 0 && ", "}
                <button className="link" onClick={() => onOpenFile(f.path)}>
                  {f.path}
                </button>
              </span>
            ))
          ) : (
            "the read-only files"
          )}
          . Hidden tests also run when you click Run.
          </span>
        </p>
      </div>
    );
  }

  const visible = problem.tests.filter((t) => t.visible);
  return (
    <FunctionCases problem={problem} visible={visible} customTests={customTests} onChangeCustom={onChangeCustom} />
  );
}

function FunctionCases({
  problem,
  visible,
  customTests,
  onChangeCustom,
}: {
  problem: Problem;
  visible: Problem["tests"];
  customTests: CustomTest[];
  onChangeCustom: (tests: CustomTest[]) => void;
}) {
  const total = visible.length + customTests.length;
  const [sel, setSel] = useState(0);
  useEffect(() => {
    if (sel >= total) setSel(Math.max(0, total - 1));
  }, [total, sel]);

  // Pills are numbered Test 1..N in one run (built-in first, then custom); the real name of a
  // built-in case is the title of its pill and the heading of the detail view.
  const cases = [
    ...visible.map((t, i) => ({ key: t.name, index: i, title: t.name, section: t.section })),
    ...customTests.map((c, i) => ({
      key: `c${i}`, index: visible.length + i, title: c.name ?? "Custom test", section: c.section,
    })),
  ];
  const groups = groupBySection(cases, problem.sections);
  const isCustom = sel >= visible.length;
  const test = isCustom ? null : visible[sel];
  const custom = isCustom ? customTests[sel - visible.length] : null;

  const addCase = () => {
    const base = test?.input ?? custom?.input ?? { args: [] };
    const input: TestInput = base.gen ? { args: [] } : { args: base.args ?? [], kwargs: base.kwargs, calls: base.calls };
    const section = test?.section ?? custom?.section ?? undefined;
    onChangeCustom([...customTests, { input: JSON.parse(JSON.stringify(input)), ...(section && { section }) }]);
    setSel(total);
  };

  return (
    <div className="panel-body">
      <CaseGroups
        groups={groups}
        sectioned={problem.sections.length > 0}
        render={(c) => (
          <button
            key={c.key}
            className={cx("pill", sel === c.index && "active")}
            onClick={() => setSel(c.index)}
            title={c.title}
          >
            Test {c.index + 1}
          </button>
        )}
        trailing={
          problem.has_reference && (
            <IconButton
              icon={Plus}
              label="Add test case"
              className="pill-add"
              onClick={addCase}
              title="Add a custom test case. The expected output comes from the reference solution."
            />
          )
        }
      />

      {test && (
        <div className="case">
          <div className="case-name">{test.name}</div>
          {test.description && <div className="muted"><Markdown source={test.description} /></div>}
          {test.input?.gen ? (
            <Value label="Input" value={`generated by ${test.input.gen} (seed ${test.input.seed ?? 0})`} mono={false} raw />
          ) : (
            paramNames(problem, test.input).map((name, i) => (
              <Value key={name} label={name} value={test.input?.args?.[i]} />
            ))
          )}
          {test.input?.kwargs && Object.keys(test.input.kwargs).length > 0 && !test.input.gen &&
            Object.entries(test.input.kwargs).map(([k, v]) => <Value key={k} label={k} value={v} />)}
          {test.input?.calls && <Value label="calls" value={test.input.calls} />}
          {test.expected !== undefined && test.expected !== null && <Value label="Expected" value={test.expected} />}
        </div>
      )}

      {custom && (
        <CustomCase
          key={sel}
          problem={problem}
          test={custom}
          onChange={(t) => onChangeCustom(customTests.map((c, i) => (i === sel - visible.length ? t : c)))}
          onDelete={() => onChangeCustom(customTests.filter((_, i) => i !== sel - visible.length))}
        />
      )}
      {total === 0 && <p className="muted">No visible test cases.</p>}
    </div>
  );
}

function CustomCase({
  problem,
  test,
  onChange,
  onDelete,
}: {
  problem: Problem;
  test: CustomTest;
  onChange: (t: CustomTest) => void;
  onDelete: () => void;
}) {
  const names = paramNames(problem, test.input);
  const [drafts, setDrafts] = useState(() => names.map((_, i) => formatValue(test.input.args?.[i] ?? null)));
  const [errors, setErrors] = useState<(string | null)[]>([]);

  const update = (i: number, text: string) => {
    const next = drafts.map((d, j) => (j === i ? text : d));
    setDrafts(next);
    const errs = next.map((d) => {
      try {
        JSON.parse(d);
        return null;
      } catch {
        return "not valid JSON";
      }
    });
    setErrors(errs);
    if (errs.every((e) => !e)) onChange({ ...test, input: { ...test.input, args: next.map((d) => JSON.parse(d)) } });
  };

  return (
    <div className="case">
      <div className="row between">
        <span className="case-name">{test.name ?? "Custom case"}</span>
        <IconButton icon={Trash2} label="Remove custom case" size={15} onClick={onDelete} />
      </div>
      <div className="field">
        <div className="field-label">Description</div>
        <input
          className="field-input"
          value={test.description ?? ""}
          placeholder="What does this case check? (optional)"
          onChange={(e) => onChange({ ...test, description: e.target.value || undefined })}
        />
      </div>
      {problem.sections.length > 0 && (
        <div className="field">
          <div className="field-label">Section</div>
          <select
            className="field-input"
            value={test.section ?? ""}
            onChange={(e) => onChange({ ...test, section: e.target.value || undefined })}
          >
            <option value="">None</option>
            {problem.sections.map((s) => (
              <option key={s.id} value={s.id}>
                {s.title}
              </option>
            ))}
          </select>
        </div>
      )}
      {names.map((name, i) => (
        <div className="field" key={name}>
          <div className="field-label">{name}</div>
          <textarea
            className={"field-input mono" + (errors[i] ? " invalid" : "")}
            value={drafts[i]}
            spellCheck={false}
            rows={Math.min(6, Math.max(1, drafts[i].split("\n").length))}
            onChange={(e) => update(i, e.target.value)}
          />
          {errors[i] && <div className="error-text">{errors[i]}</div>}
        </div>
      ))}
      <p className="muted small">Expected output is computed by the reference solution.</p>
    </div>
  );
}
